#!/usr/bin/env node
// Regenerates lib/legacy-copy-hashes.mjs from git history: every version of
// the skills and the filler agent that a `skel install` could have copied into
// a project, normalized the way lib/legacy-copy.mjs compares them. Run from a
// full clone after changing a skill or the agent:
//   node scripts/dev/legacy-copy-hashes.mjs > lib/legacy-copy-hashes.mjs
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import { copyHash, renderLegacy } from "../../lib/legacy-copy.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const git = (...a) => execFileSync("git", ["-C", root, ...a], { encoding: "utf-8", maxBuffer: 64 << 20 });
const FILES = ["skills/skeleton/SKILL.md", "skills/skeleton-fill/SKILL.md", "agents/skeleton-filler.md"];
const out = {};
for (const rel of FILES) {
  const hashes = new Set();
  for (const h of git("log", "--format=%H", "HEAD", "--", rel).split("\n").filter(Boolean)) {
    let text;
    try { text = git("show", `${h}:${rel}`); } catch { continue; }
    hashes.add(copyHash(renderLegacy(text, "/x")));
  }
  hashes.add(copyHash(renderLegacy(fs.readFileSync(path.join(root, rel), "utf-8"), "/x")));
  out[rel] = [...hashes].sort();
}
process.stdout.write(`// Generated by scripts/dev/legacy-copy-hashes.mjs; don't edit by hand.
// sha256 of every released skill/agent text, as lib/legacy-copy.mjs normalizes a project copy.
export const LEGACY_COPY_HASHES = ${JSON.stringify(out, null, 2)};
`);
